export const getTranslatedServiceName = (name: string, lang: Language): string => {
  if (lang === 'en' || !name) return name;
  const directMatch = SERVICE_NAME_TRANSLATIONS[lang]?.[name];
  if (directMatch) return directMatch;

  // Search partial matches
  for (const [enKey, trVal] of Object.entries(SERVICE_NAME_TRANSLATIONS[lang] || {})) {
    if (name.toLowerCase().includes(enKey.toLowerCase()) || enKey.toLowerCase().includes(name.toLowerCase())) {
      return trVal;
    }
  }

  return name;
};

