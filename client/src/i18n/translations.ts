export const getTranslatedSectorTitle = (sectorId: string, fallback: string, lang: Language): string => {
  if (lang === 'en') return fallback;
  return SECTOR_TRANSLATIONS[lang]?.[sectorId] || fallback;
};

export const getTranslatedServiceName = (name: string, lang: Language): string => {
  if (lang === 'en' || !name) return name;
  const directMatch = SERVICE_NAME_TRANSLATIONS[lang]?.[name];
  if (directMatch) return directMatch;

  // Search partial matches
  for (const [enKey, trVal] of Object.entries(SERVICE_NAME_TRANSLATIONS[lang] || {})) {
    if (name.toLowerCase().includes(enKey.toLowerCase()) || enKey.toLowerCase().includes(name.toLowerCase())) {
      return trVal;
    }
  }

  return name;
};

export const getTranslatedDuration = (duration: string = '', lang: Language): string => {
  if (lang === 'en' || !duration) return duration;
  if (lang === 'hi') {
    return duration
      .replace(/(\d+)\s*hrs?/gi, '$1 घंटे')
      .replace(/(\d+)\s*mins?/gi, '$1 मिनट')
      .replace(/(\d+)\s*Days?/gi, '$1 दिन')
      .replace(/Monthly SLA/gi, 'मासिक SLA')
      .replace(/Consultation/gi, 'परामर्श')
      .replace(/Select Persons & Days/gi, 'श्रमिक व दिन चुनें')
      .replace(/1 Year/gi, '1 वर्ष')
      .replace(/365 Days/gi, '365 दिन');
  }
  if (lang === 'mr') {
    return duration
      .replace(/(\d+)\s*hrs?/gi, '$1 तास')
      .replace(/(\d+)\s*mins?/gi, '$1 मिनिटे')
      .replace(/(\d+)\s*Days?/gi, '$1 दिवस')
      .replace(/Monthly SLA/gi, 'मासिक SLA')
      .replace(/Consultation/gi, 'सल्लागार')
      .replace(/Select Persons & Days/gi, 'कामगार व दिवस निवडा')
      .replace(/1 Year/gi, '१ वर्ष')
      .replace(/365 Days/gi, '३६५ दिवस');
  }
  return duration;
};
